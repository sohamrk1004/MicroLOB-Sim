import json
from pathlib import Path

from experiments.deterministic_replay import (
    create_event_sequence,
    replay_events
)


def build_structured_records(event_history):
    records = []

    for item in event_history:
        event_number = item["event_number"]

        # Record the input event.
        records.append({
            "record_type": "EVENT",
            "event_number": event_number,
            "event": item["event"]
        })

        # Record the resulting book state.
        records.append({
            "record_type": "STATE_TRANSITION",
            "event_number": event_number,
            "state_before": item["state_before"],
            "state_after": item["state_after"]
        })

        # Record each trade generated by this event.
        for trade in item["trades"]:
            records.append({
                "record_type": "EXECUTION",
                "event_number": event_number,
                "trade": trade
            })

    return records


def write_jsonl(records, output_path):
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with output_path.open("w", encoding="utf-8") as file:
        for record in records:
            file.write(
                json.dumps(record, sort_keys=True) + "\n"
            )


def main():
    events = create_event_sequence()

    event_history, final_state = replay_events(events)

    records = build_structured_records(event_history)

    output_path = Path("results/replay_log.jsonl")

    write_jsonl(records, output_path)

    print(f"Structured log saved to: {output_path}")
    print(f"Total records: {len(records)}")
    print(f"Total executions: {len(final_state['trades'])}")
    print(
        "Quantity conservation:",
        final_state["quantity_conserved"]
    )


if __name__ == "__main__":
    main()